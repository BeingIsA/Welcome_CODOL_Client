"""运行端口：版本适配可用的受控进程和事件接口。"""
from typing import Protocol

class PeriodicTrigger(Protocol):
    def due(self, force: bool=False) -> bool: ...

class ProcessAccess(Protocol):
    @property
    def main_thread_id(self) -> int: ...
    def context(self, tid: int) -> tuple: ...
    def set_context(self, thread, ctx) -> None: ...
    def close_thread(self, thread) -> None: ...
    def cstring(self, address, wide=False, strict=False) -> str: ...
    def regions(self) -> list: ...
    def read(self, address: int, size: int) -> bytes: ...
    def write(self, address: int, data: bytes) -> None: ...
    def allocate(self, size: int=4096) -> int: ...
    def executable(self, address: int, size: int=4096) -> None: ...
    def periodic(self, interval: float) -> PeriodicTrigger: ...

class GameEvents(Protocol):
    def bind_debugger(self, debugger: DebugControl) -> None: ...
    def idle(self) -> None: ...
    def module_loaded(self, base: int) -> None: ...
    def handle_exception(self, event, code: int, address: int, row: dict) -> bool: ...
    def breakpoint(self, event, address, original, label, row, thread, ctx) -> None: ...


class DebugControl(Protocol):
    """版本事件可调用的断点机制。"""
    def arm(self, address: int, label: str) -> None: ...
    def install_file_trace(self) -> None: ...
